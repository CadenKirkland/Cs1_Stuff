public class JavaForEach1 {
    public static void main(String[] args){

        String[] pets = { "dog", "cat", "bird"};

        for(String x : pets){
            System.out.println(x);
        }
        //.....................................................
        int[] codes = {3213, 9604, 6109, 4388, 2913};

        for (int z : codes){
            System.out.println(z);
        }
    }
}
